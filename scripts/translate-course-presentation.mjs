// AR, ZH, JP, EL : pour ces langues, on remplace le texte FR complet par une traduction complète
// car le remplacement phrase par phrase ne fonctionne pas bien avec les scripts non-latins.
// On traduit les parties descriptives, les noms de champs JSON restent en anglais.

// Fonction d'application des mappings
function applyMappings(frText, mappings) {
  let result = frText;
  for (const [search, replace] of mappings) {
    // Utilise une regex pour permettre les patterns regex dans search
    try {
      const regex = new RegExp(search.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g');
      result = result.replace(regex, replace);
    } catch (e) {
      result = result.replaceAll(search, replace);
    }
  }
  return result;
}

